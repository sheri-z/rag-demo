"""HTTP API for the RAG demo.

Endpoints:
    GET  /health      liveness check, no key needed
    GET  /companies   companies in the knowledge base
    POST /ask         answer a question (knowledge base, or web search fallback)
    GET  /docs        interactive Swagger UI, generated by FastAPI

Every /ask call costs OpenAI credits, so the API is locked down by default:
    - clients must send the API_KEY from .env in the X-API-Key header (the server will not
      start without one)
    - per-IP rate limit and a daily cap on all requests (in memory, reset on restart)
    - errors return a short message; details only go to the server log
    - the server binds to 127.0.0.1; public access goes through a tunnel (see README)

Usage:
    uv run python -m rag_demo.api                 # http://127.0.0.1:8000/docs
"""

import asyncio
import logging
import secrets
import time
from collections import defaultdict, deque
from contextlib import asynccontextmanager
from datetime import date
from typing import Annotated, Literal

import uvicorn
from fastapi import Depends, FastAPI, HTTPException, Request, Security
from fastapi.responses import JSONResponse
from fastapi.security import APIKeyHeader
from pydantic import BaseModel, Field

from rag_demo.config import get_settings
from rag_demo.router import companies
from rag_demo.workflow import run

logger = logging.getLogger("rag_demo.api")

HOST, PORT = "127.0.0.1", 8000
ASK_TIMEOUT_SECONDS = 120


# --- schemas -----------------------------------------------------------------


class AskRequest(BaseModel):
    question: str = Field(min_length=3, max_length=500, examples=[
        "What was the Dividend per share (in USD) for Ritchie Bros. Auctioneers Incorporated?"
    ])  # fmt: skip
    kind: Literal["number", "boolean", "name", "names"] | None = Field(
        default=None, description="Answer type. Detected automatically if omitted."
    )


class PageReference(BaseModel):
    company: str
    page: int


class WebSource(BaseModel):
    title: str
    url: str


class AskResponse(BaseModel):
    question: str
    kind: str
    kind_detected: bool
    answer: str | float | int | bool | list[str]
    source: Literal["knowledge_base", "web"]
    company: str | None
    references: list[PageReference] = Field(description="Report pages, for knowledge base answers")
    web_sources: list[WebSource] = Field(description="URLs, for web answers")
    reasoning_summary: str
    fallback_reason: str | None = Field(description="Why the web was used, if it was")
    trace: list[str] = Field(description="Workflow steps taken")
    seconds: float


class Company(BaseModel):
    name: str
    sha1: str


# --- access control ----------------------------------------------------------

api_key_header = APIKeyHeader(name="X-API-Key", auto_error=False)


def require_api_key(key: Annotated[str | None, Security(api_key_header)]) -> None:
    expected = get_settings().api_key.get_secret_value()
    if not key or not secrets.compare_digest(key.encode(), expected.encode()):
        raise HTTPException(status_code=401, detail="missing or invalid X-API-Key")


def client_ip(request: Request) -> str:
    # Behind a Cloudflare tunnel every request comes from 127.0.0.1; Cloudflare passes the
    # real client address in this header. The server only listens on 127.0.0.1, so the
    # header cannot be set by someone bypassing the tunnel.
    return request.headers.get("cf-connecting-ip") or (
        request.client.host if request.client else "unknown"
    )


class Limiter:
    def __init__(self) -> None:
        self.recent: dict[str, deque[float]] = defaultdict(deque)
        self.day = date.today()
        self.today = 0

    def check(self, ip: str) -> None:
        settings = get_settings()
        now = time.monotonic()
        window = self.recent[ip]
        while window and now - window[0] > 60:
            window.popleft()
        if len(window) >= settings.rate_limit_per_minute:
            raise HTTPException(429, "rate limit exceeded, try again in a minute")
        if date.today() != self.day:
            self.day, self.today = date.today(), 0
        if self.today >= settings.daily_request_limit:
            raise HTTPException(429, "daily request limit reached")
        window.append(now)
        self.today += 1


limiter = Limiter()


def rate_limit(request: Request) -> None:
    limiter.check(client_ip(request))


# --- app ---------------------------------------------------------------------


@asynccontextmanager
async def lifespan(app: FastAPI):
    if get_settings().api_key is None:
        raise RuntimeError("set API_KEY in .env before starting the API")
    companies()  # load the routing list now, so a missing metadata.json fails at startup
    yield


app = FastAPI(
    title="rag-demo",
    description="Question answering over 5 annual reports, with web search fallback over MCP.",
    version="0.1.0",
    lifespan=lifespan,
)


@app.exception_handler(Exception)
async def unhandled_error(request: Request, exc: Exception) -> JSONResponse:
    logger.exception("unhandled error on %s", request.url.path)
    return JSONResponse(status_code=500, content={"detail": "internal error"})


@app.get("/health")
def health() -> dict:
    return {"status": "ok"}


@app.get("/companies", dependencies=[Depends(require_api_key)])
def list_companies() -> list[Company]:
    return [Company(name=c.name, sha1=c.sha1) for c in companies()]


@app.post("/ask", dependencies=[Depends(require_api_key), Depends(rate_limit)])
async def ask(body: AskRequest) -> AskResponse:
    start = time.perf_counter()
    try:
        state = await asyncio.wait_for(run(body.question, body.kind), ASK_TIMEOUT_SECONDS)
    except TimeoutError:
        raise HTTPException(504, "the question took too long to answer") from None
    a = state["answer"]
    return AskResponse(
        question=body.question,
        kind=state["kind"],
        kind_detected=state.get("kind_detected", False),
        answer=a.value,
        source=a.source,
        company=a.company,
        references=[PageReference(company=a.company, page=r["page"]) for r in a.references],
        web_sources=[WebSource(**s) for s in a.web_sources],
        reasoning_summary=a.reasoning_summary,
        fallback_reason=state.get("fallback_reason"),
        trace=state["trace"],
        seconds=round(time.perf_counter() - start, 1),
    )


def main() -> None:
    logging.basicConfig(level=logging.INFO)
    uvicorn.run(app, host=HOST, port=PORT)


if __name__ == "__main__":
    main()
